import { Body, Controller, Delete, Get, HttpCode, Param, Patch, Post, UseGuards, UsePipes, ValidationPipe } from "@nestjs/common";
import { ApiBearerAuth, ApiCreatedResponse, ApiNoContentResponse, ApiOkResponse, ApiOperation, ApiResponse, ApiTags } from "@nestjs/swagger";
import { AuthGuard } from "../auth/auth.guard";
import { PrivilegesGuard, RequirePrivileges } from "../auth/privileges.guard";
import { ApiErrorDto } from "../openapi/response.dto";
import { CreatePartnerDto, PartnerIdDto, PartnerResponseDto, UpdatePartnerDto } from "./dto/partner.dto";
import { PartnersService } from "./partners.service";

@ApiTags("partners")
@Controller("partners")
@UsePipes(new ValidationPipe({ transform: true, whitelist: true, forbidNonWhitelisted: true }))
@ApiResponse({ status: 400, type: ApiErrorDto })
@ApiResponse({ status: 404, type: ApiErrorDto })
export class PartnersController {
  constructor(private readonly partners: PartnersService) {}

  @Get()
  @ApiOperation({ summary: "List partners", description: "Public partner data including contact fields. Ordered by id." })
  @ApiOkResponse({ type: PartnerResponseDto, isArray: true })
  list() { return this.partners.list(); }

  @Get(":id")
  @ApiOperation({ summary: "Get partner" })
  @ApiOkResponse({ type: PartnerResponseDto })
  get(@Param() { id }: PartnerIdDto) { return this.partners.get(id); }

  @Post()
  @UseGuards(AuthGuard, PrivilegesGuard)
  @RequirePrivileges("settings.update")
  @ApiBearerAuth()
  @ApiOperation({ summary: "Create partner", description: "Requires settings.update. ID is generated by the server." })
  @ApiCreatedResponse({ type: PartnerResponseDto })
  @ApiResponse({ status: 401, type: ApiErrorDto })
  @ApiResponse({ status: 403, type: ApiErrorDto })
  create(@Body() dto: CreatePartnerDto) { return this.partners.create(dto); }

  @Patch(":id")
  @UseGuards(AuthGuard, PrivilegesGuard)
  @RequirePrivileges("settings.update")
  @ApiBearerAuth()
  @ApiOperation({ summary: "Update partner", description: "Requires settings.update. Omitted fields are preserved; null clears optional fields." })
  @ApiOkResponse({ type: PartnerResponseDto })
  @ApiResponse({ status: 401, type: ApiErrorDto })
  @ApiResponse({ status: 403, type: ApiErrorDto })
  update(@Param() { id }: PartnerIdDto, @Body() dto: UpdatePartnerDto) { return this.partners.update(id, dto); }

  @Delete(":id")
  @UseGuards(AuthGuard, PrivilegesGuard)
  @RequirePrivileges("settings.update")
  @ApiBearerAuth()
  @ApiOperation({ summary: "Delete partner", description: "Requires settings.update." })
  @HttpCode(204)
  @ApiNoContentResponse()
  @ApiResponse({ status: 401, type: ApiErrorDto })
  @ApiResponse({ status: 403, type: ApiErrorDto })
  delete(@Param() { id }: PartnerIdDto) { return this.partners.delete(id); }
}
